#!/usr/bin/env python3
"""Write docs/evidence/OUTCOME_EVIDENCE.md, the evidence file handed to /evidence-gates:outcome for
docs/PREREGISTRATION.md. Every fenced block is the raw output of the command printed above it, run now.

Commands are chosen so that their output holds no commit hash of another repository: the doc-citation guard reads any
7-40 hex run in a tracked doc (fenced or not) as a citation of this repository. Where a hash had to be hidden, the
command line itself shows the `sed` that hides it.

  outcome_evidence.py <repo-root> <runs-dir>
"""
from __future__ import annotations

import os
import subprocess
import sys

ROOT, RUNS = sys.argv[1], sys.argv[2]
SNAP = RUNS + "/p2-plugin/snap"
PF = "docs/prereg/calc-py-prints-42_PREDICTION.md"
TAG = "prereg/calc-py-prints-42"
out: list[str] = []


def w(text: str = "") -> None:
    out.append(text)


def run(command: str, shown: str | None = None) -> None:
    p = subprocess.run(["/bin/bash", "-c", command], cwd=ROOT, capture_output=True, text=True)
    body = (p.stdout + p.stderr).rstrip("\n")
    assert "```" not in body, command
    w("```console")
    w("$ " + (shown or command).replace(RUNS, "<runs>"))
    w(body.replace(RUNS, "<runs>"))
    w("```")


w("# Evidence for the outcome of `docs/PREREGISTRATION.md`")
w()
w("Prepared for `/evidence-gates:outcome docs/PREREGISTRATION.md docs/evidence/OUTCOME_EVIDENCE.md`, generated by "
  "`tests/p2p3/outcome_evidence.py`. Each fenced block is the raw output of the command shown above it, run when "
  "this file was generated; `<runs>` stands for the harness's run directory outside the repository.")
w()
w("**For the outcome step.** Carry each prediction's verdict, its one-line reason, its N and its fenced output into "
  "the Outcome section, one `### P<n> — <VERDICT>` section per prediction, with its evidence link. Carry the block "
  "under \"Carried verbatim\" word for word into `### Supplementary (not registered)`.")
w()

